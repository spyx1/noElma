        $createdNodes = 0;
        $assignments = 0;
        $groupNodes = 0;

        DB::transaction(function () use (
            $rows,
            &$createdUsers,
            &$existingUsers,
            &$importedUserIds,
            &$createdNodes,
            &$assignments,
            &$groupNodes
        ): void {
            /* Импорт является полной синхронизацией с Excel. */
            DB::table('company_structure_node_user')->delete();
            CompanyStructureNode::query()->delete();

            /** @var array<string, User> $usersByName */
            $usersByName = [];

            foreach (User::query()->get() as $user) {
                $displayName = trim($user->displayName());
                $storedName = trim((string) $user->name);

                if ($displayName !== '') {
                    $usersByName[$this->normalizeName($displayName)] = $user;
                }

                if ($storedName !== '') {
                    $usersByName[$this->normalizeName($storedName)] = $user;
                }
            }

            /** @var array<int, int> $levelNodeIds */
            $levelNodeIds = [];

            /** @var array<string, CompanyStructureNode> $nodesByParentAndTitle */
            $nodesByParentAndTitle = [];

            /** @var array<string, int> $sortOrders */
            $sortOrders = [];

            /** @var array<int, array<int, true>> $assignedUserIds */
            $assignedUserIds = [];

            foreach ($rows as $sourceRow) {
                $level = (int) $sourceRow['level'];
                $title = trim((string) $sourceRow['title']);
                $fio = trim((string) $sourceRow['fio']);

                $parentId = null;

                if ($level > 0) {
                    $parentId = $levelNodeIds[$level - 1] ?? null;

                    if (!$parentId) {
                        throw new RuntimeException(
                            'Не найден родитель для строки оргструктуры: ' . $title
                        );
                    }
                }

                $nodeKey = ($parentId ?? 0) . '|' . $this->normalizeName($title);
                $node = $nodesByParentAndTitle[$nodeKey] ?? null;

                if (!$node) {
                    $sortKey = (string) ($parentId ?? 0);
                    $sortOrders[$sortKey] = ($sortOrders[$sortKey] ?? 0) + 1;

                    $node = CompanyStructureNode::query()->create([
                        'parent_id' => $parentId,
                        'title' => $title,
                        'allows_multiple_users' => false,
                        'sort_order' => $sortOrders[$sortKey],
                    ]);

                    $nodesByParentAndTitle[$nodeKey] = $node;
                    $createdNodes++;
                }

                $levelNodeIds[$level] = $node->id;

                foreach (array_keys($levelNodeIds) as $knownLevel) {
                    if ($knownLevel > $level) {
                        unset($levelNodeIds[$knownLevel]);
                    }
                }

                if ($fio === '') {
                    continue;
                }

                $userKey = $this->normalizeName($fio);
                $user = $usersByName[$userKey] ?? null;

                if (!$user) {
                    [$lastName, $firstName, $middleName] = $this->splitFio($fio);

                    $user = User::query()->create([
                        'name' => $fio,
                        'last_name' => $lastName,
                        'first_name' => $firstName,
                        'middle_name' => $middleName,
                        'email' => null,
                        'phone' => null,
                        'avatar_mode' => 'initials',
                        'password' => null,
                        'is_admin' => false,
                        'role' => User::ROLE_EMPLOYEE,
                    ]);

                    $usersByName[$userKey] = $user;
                    $createdUsers++;
                }

                if (!isset($importedUserIds[$user->id])) {
                    $importedUserIds[$user->id] = true;

                    if (!$user->wasRecentlyCreated) {
                        $existingUsers++;
                    }
                }

                if (!isset($assignedUserIds[$node->id][$user->id])) {
                    $node->users()->attach($user->id);
                    $assignedUserIds[$node->id][$user->id] = true;
                    $assignments++;
                }
            }

            foreach ($nodesByParentAndTitle as $node) {
                $userCount = isset($assignedUserIds[$node->id])
                    ? count($assignedUserIds[$node->id])
                    : 0;

                if ($userCount > 1) {
                    $node->forceFill(['allows_multiple_users' => true])->save();
                    $groupNodes++;
                }
            }
        });

        $this->command?->info('Импорт структуры компании завершён.');
        $this->command?->info('Узлов создано: ' . $createdNodes);
        $this->command?->info('Групповых должностей: ' . $groupNodes);
        $this->command?->info('Назначений пользователей: ' . $assignments);
        $this->command?->info('Новых пользователей создано: ' . $createdUsers);
        $this->command?->info('Пользователей найдено в Laravel: ' . $existingUsers);
    }

    private function normalizeName(string $value): string
    {
        $value = preg_replace('/\s+/u', ' ', trim($value)) ?? trim($value);

        return Str::lower($value);
    }

    /** @return array{0:string,1:string,2:?string} */
    private function splitFio(string $fio): array
    {
        $parts = preg_split('/\s+/u', trim($fio)) ?: [];

        $lastName = (string) ($parts[0] ?? '');
        $firstName = (string) ($parts[1] ?? '');
        $middleName = count($parts) > 2
            ? implode(' ', array_slice($parts, 2))
            : null;

        return [$lastName, $firstName, $middleName];
    }
